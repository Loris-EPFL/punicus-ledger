import kotlinx.serialization.json.jsonPrimitive
import org.kotlincrypto.hash.sha2.SHA256

/**
 * [ClearSigningCatalog] over the catalog built into this release ([CLEAR_SIGNING_CATALOG_JSON], generated by
 * `scripts/clear-signing/generate.py` from the pinned registry files; docs/clear-signing.md, A1). It is read
 * once, after its sha256 is checked against [CLEAR_SIGNING_CATALOG_SHA256]: text that is not the generated
 * catalog, or that this reader cannot read in full, gives an empty catalog, so every call stays not decoded,
 * never a partial one. Nothing is fetched. Each `$.metadata` reference is resolved here, so the descriptors
 * it gives hold values only.
 */
class BuiltInClearSigningCatalog internal constructor(
    private val chunks: List<String>,
    private val sha256: String,
) : ClearSigningCatalog {

    /** The catalog of this release. */
    constructor() : this(CLEAR_SIGNING_CATALOG_JSON, CLEAR_SIGNING_CATALOG_SHA256)

    /** Every deployment, by network and address; empty when the text is not the catalog it should be. */
    val deployments: Map<Pair<Network, Address>, ClearSigningDeployment> by lazy {
        val text = chunks.joinToString("")
        val digest = SHA256().digest(text.encodeToByteArray()).joinToString("") { (it.toInt() and 0xff).toString(16).padStart(2, '0') }
        if (digest != sha256) {
            emptyMap()
        } else {
            runCatching { read(Json.parseToJsonElement(text).jsonObject) }.getOrElse { emptyMap() }
        }
    }

    override fun deployment(network: Network, address: Address): ClearSigningDeployment? = deployments[network to address]

    private fun read(catalog: JsonObject): Map<Pair<Network, Address>, ClearSigningDeployment> {
        val sources = catalog.obj("descriptors")
        val descriptors = sources.mapValues { (path, value) -> descriptor(path, value.jsonObject) }
        return catalog.array("deployments").map { it.jsonObject }.associate { entry ->
            val network = Network.valueOf(entry.text("network"))
            require(network.chainId == entry.long("chainId"))
            val address = Address.of(entry.text("address"))
            val upgrade = entry.obj("upgrade")
            val deployment = ClearSigningDeployment(
                network = network,
                name = entry.text("name"),
                address = address,
                codeHash = entry.text("codeHash"),
                codePin = codePin(upgrade),
                descriptors = entry.array("descriptors").map { descriptors.getValue(it.jsonPrimitive.content) },
                delegatesToItself = listOf("delegatecall", "implementationDelegatecall").any { key ->
                    (upgrade[key] as? JsonObject)?.get("self")?.jsonPrimitive?.booleanOrNull == true
                },
            )
            (network to address) to deployment
        }
    }

    private fun codePin(upgrade: JsonObject): CodePin = when (upgrade.text("kind")) {
        "none" -> CodePin.Fixed
        "slot" -> CodePin.Slot(upgrade.text("slot"), Address.of(upgrade.text("implementation")), upgrade.text("implementationCodeHash"))
        "call" -> CodePin.Call(upgrade.text("selector"), upgrade.text("returns"), upgrade.text("implementationCodeHash"))
        else -> throw IllegalArgumentException("upgrade kind")
    }

    private fun descriptor(path: String, entry: JsonObject): ClearSigningDescriptor {
        val constants = (entry["constants"] as? JsonObject) ?: JsonObject(emptyMap())
        val kind = when (entry.text("kind")) {
            "calldata" -> ClearSigningDescriptor.Kind.CALLDATA
            "eip712" -> ClearSigningDescriptor.Kind.EIP712
            else -> throw IllegalArgumentException("kind")
        }
        val domain = entry["domain"] as? JsonObject
        val enums = ((entry["enums"] as? JsonObject) ?: JsonObject(emptyMap())).mapValues { (_, values) ->
            values.jsonObject.mapValues { it.value.jsonPrimitive.content }
        }
        val formats = entry.array("formats").map { format(it.jsonObject, kind, constants) }
        return ClearSigningDescriptor(
            source = path,
            sha256 = entry.text("sha256"),
            owner = entry.text("owner"),
            kind = kind,
            domainName = (domain?.get("name") as? JsonPrimitive)?.content,
            domainVersion = (domain?.get("version") as? JsonPrimitive)?.content,
            enums = enums,
            formats = formats,
        )
    }

    private fun format(entry: JsonObject, kind: ClearSigningDescriptor.Kind, constants: JsonObject): ClearSigningFormat {
        val key = entry.text("key")
        val function = if (kind == ClearSigningDescriptor.Kind.CALLDATA) {
            requireNotNull(AbiFunction.parse(key)).also { require(it.selector == entry.text("selector")) }
        } else {
            null
        }
        return ClearSigningFormat(
            key = key,
            function = function,
            selector = function?.selector,
            encodeType = key.takeIf { kind == ClearSigningDescriptor.Kind.EIP712 },
            typeHash = (entry["typeHash"] as? JsonPrimitive)?.content,
            primaryType = (entry["primaryType"] as? JsonPrimitive)?.content,
            intent = entry.text("intent"),
            interpolatedIntent = (entry["interpolatedIntent"] as? JsonPrimitive)?.content,
            fields = entry.array("fields").map { field(it.jsonObject, constants) },
        )
    }

    private fun field(entry: JsonObject, constants: JsonObject): ClearSigningField {
        val children = (entry["fields"] as? JsonArray)?.map { field(it.jsonObject, constants) } ?: emptyList()
        val params = (entry["params"] as? JsonObject) ?: JsonObject(emptyMap())
        fun param(name: String): JsonElement? = params[name]?.let { resolve(it, constants) }
        val format = (entry["format"] as? JsonPrimitive)?.content?.let { name -> fieldFormat(name, ::param) }
        return ClearSigningField(
            path = (entry["path"] as? JsonPrimitive)?.content?.let { requireNotNull(ClearSigningPath.parse(it)) },
            label = (entry["label"] as? JsonPrimitive)?.content,
            format = format,
            visibility = visibility(entry["visible"]),
            children = children,
            iteration = when ((entry["iteration"] as? JsonPrimitive)?.content) {
                null, "sequential" -> ClearSigningField.Iteration.SEQUENTIAL
                "bundled" -> ClearSigningField.Iteration.BUNDLED
                else -> throw IllegalArgumentException("iteration")
            },
        )
    }

    private fun fieldFormat(name: String, param: (String) -> JsonElement?): FieldFormat {
        fun path(key: String) = param(key)?.let { requireNotNull(ClearSigningPath.parse(it.jsonPrimitive.content)) }
        fun addresses(key: String): Set<Address> = when (val value = param(key)) {
            null -> emptySet()
            is JsonArray -> value.map { Address.of(it.jsonPrimitive.content) }.toSet()
            else -> setOf(Address.of(value.jsonPrimitive.content))
        }
        fun words(key: String): Set<String> = (param(key) as? JsonArray)?.map { it.jsonPrimitive.content }?.toSet() ?: emptySet()
        return when (name) {
            "raw" -> FieldFormat.Raw
            "amount" -> FieldFormat.Amount
            "tokenAmount" -> FieldFormat.TokenAmount(
                tokenPath = path("tokenPath"),
                token = param("token")?.let { Address.of(it.jsonPrimitive.content) },
                nativeCurrency = addresses("nativeCurrencyAddress"),
                threshold = param("threshold")?.let { uint(it.jsonPrimitive) },
                message = param("message")?.jsonPrimitive?.content,
            )
            "addressName" -> FieldFormat.AddressName(addresses("senderAddress"), words("types"), words("sources"))
            "date" -> FieldFormat.Date(blockHeight = param("encoding")?.jsonPrimitive?.content == "blockheight")
            "duration" -> FieldFormat.Duration
            "unit" -> FieldFormat.Unit(
                base = requireNotNull(param("base")).jsonPrimitive.content,
                decimals = param("decimals")?.jsonPrimitive?.intOrNull ?: 0,
                prefix = param("prefix")?.jsonPrimitive?.booleanOrNull ?: false,
            )
            "enum" -> FieldFormat.Enum(requireNotNull(enumName(param)))
            "chainId" -> FieldFormat.ChainId
            "calldata" -> FieldFormat.Calldata(requireNotNull(path("calleePath")))
            "nftName" -> FieldFormat.NftName(requireNotNull(path("collectionPath")))
            "tokenTicker" -> FieldFormat.TokenTicker
            else -> throw IllegalArgumentException("format $name")
        }
    }

    // An enum's `$ref` names it (`$.metadata.enums.<name>`): left unresolved by [resolve], read here.
    private fun enumName(param: (String) -> JsonElement?): String? =
        param("\$ref")?.jsonPrimitive?.content?.removePrefix("\$.metadata.enums.")

    /** A `$.metadata.constants.<name>` reference replaced by the constant, in lists too; anything else as it is. */
    private fun resolve(value: JsonElement, constants: JsonObject): JsonElement = when (value) {
        is JsonArray -> JsonArray(value.map { resolve(it, constants) })
        is JsonPrimitive -> value.content.takeIf { value.isString && it.startsWith(CONSTANT) }
            ?.let { requireNotNull(constants[it.removePrefix(CONSTANT)]) } ?: value
        else -> value
    }

    private fun visibility(value: JsonElement?): Visibility = when (value) {
        null -> Visibility.Shown
        is JsonPrimitive -> when (value.content) {
            "always", "optional" -> Visibility.Shown
            "never" -> Visibility.Hidden
            else -> throw IllegalArgumentException("visible")
        }
        is JsonObject -> {
            val (rule, values) = value.entries.single()
            val keys = values.jsonArray.map { key(it.jsonPrimitive) }.toSet()
            when (rule) {
                "mustMatch" -> Visibility.MustMatch(keys)
                "ifNotIn" -> Visibility.ShownUnless(keys)
                else -> throw IllegalArgumentException("visible rule")
            }
        }
        else -> throw IllegalArgumentException("visible")
    }

    /** A listed value as [eth.serotine.domain.model.ClearSignFormatter.key] writes one: decimal integers, lower-case hex. */
    private fun key(value: JsonPrimitive): String {
        val text = value.content
        return when {
            !value.isString && text != "true" && text != "false" -> requireNotNull(UInt256.parse(text)).toDecimal()
            text.startsWith("0x") -> text.lowercase()
            else -> text
        }
    }

    private fun uint(value: JsonPrimitive): UInt256 {
        val text = value.content
        return if (text.startsWith("0x")) {
            UInt256.fromBigEndian(text.removePrefix("0x").padStart(64, '0').chunked(2).map { it.toInt(16).toByte() }.toByteArray())
        } else {
            requireNotNull(UInt256.parse(text))
        }
    }

    private fun JsonObject.text(key: String): String = getValue(key).jsonPrimitive.content
    private fun JsonObject.long(key: String): Long = getValue(key).jsonPrimitive.content.toLong()
    private fun JsonObject.obj(key: String): JsonObject = getValue(key).jsonObject
    private fun JsonObject.array(key: String): JsonArray = getValue(key).jsonArray

    private companion object {
        const val CONSTANT = "\$.metadata.constants."
    }
}
