/**
 * The queueing of a Gnosis Pay transfer through member Safes ([DelayTransfer.queueCall]; owner's
 * request, 2026-11-17), against call data built independently of this code, by the encoder whose
 * output for a real account a verified `eth_call` on Gnosis Chain accepted: a key that owns a Delay
 * member Safe of threshold 1 queueing 1 EURe out of that Delay's Gnosis Pay account. The addresses
 * here are made up; only EURe's is real.
 */
class DelayTransferQueueCallTest {

    private val safe = Address.of("0x" + "5a".repeat(20))
    private val delay = Address.of("0x" + "de".repeat(20))
    private val memberSafe = Address.of("0x" + "11".repeat(20))
    private val ownerSafe = Address.of("0x" + "a2".repeat(20))
    private val key = Address.of("0x" + "91".repeat(20))
    private val eure = Token(Address.of("0x420ca0f9b9b604ce0fd9c18ef134c705e5fa3430"), "EURe", "Monerium EURe", 18, null)

    private val transfer = (
        DelayTransfer.of(
            safe,
            delay,
            emptyList(),
            TransferAsset.Erc20Token(eure),
            key,
            UInt256.parseUnits("1", 18)!!,
        ) as DelayTransferPlan.Planned
        ).transfer

    @Test
    fun aMemberSendsTheQueueingStraightToTheDelay() {
        val (to, data) = transfer.queueCall(key, via = emptyList())

        assertEquals(delay, to)
        assertEquals(transfer.queueData().toHex(), data.toHex())
    }

    @Test
    fun theOwnerOfAMemberSafeSendsItThroughThatSafeConfirmedAsTheOneExecuting() {
        val (to, data) = transfer.queueCall(key, via = listOf(memberSafe))

        assertEquals(memberSafe, to)
        assertEquals(ONE_SAFE, data.toHex().removePrefix("0x"))
    }

    @Test
    fun eachSafeOnTheWayIsConfirmedByTheOneBelowIt() {
        val (to, data) = transfer.queueCall(key, via = listOf(memberSafe, ownerSafe))

        // The key sends to the Safe it owns; that Safe confirms the member Safe's call.
        assertEquals(ownerSafe, to)
        assertEquals(TWO_SAFES, data.toHex().removePrefix("0x"))
    }

