#!/usr/bin/env python3
"""Writes the verified-ABI catalog (docs/clear-signing.md, *Phase C*) from what the recompile vouched for.

    python3 -I scripts/verified-abis/generate.py           # writes data/.../clearsigning/VerifiedAbiCatalog.kt
    python3 -I scripts/verified-abis/generate.py --check   # fails if the committed file is not what it writes

Reads verified.json (verify.mjs's output: each contract's network, code hash, compiled name and functions, from
the recompile alone) and contracts.json (the list: which network each chain id is, and which implementations
are pinned with their EIP-1167 minimal proxy). For such an implementation it adds the proxy's runtime code
hash, held to the implementation's network and to the implementation's own pin, which the app checks before
it names the proxy's call. Nothing here is fetched: a refresh runs fetch.py, verify.mjs and
check_code_hashes.py first.
"""
import hashlib
import json
import pathlib
import sys

HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parent.parent
sys.path.insert(0, str(HERE.parent / "clear-signing"))
from keccak import keccak256  # noqa: E402

TARGET = ROOT / "data/src/commonMain/kotlin/eth/serotine/data/clearsigning/VerifiedAbiCatalog.kt"
CHUNK_BYTES = 60_000  # a JVM class file holds a string constant of at most 65535 bytes

# EIP-1167: the runtime code of a minimal proxy, the implementation's address between the two halves.
EIP1167_PREFIX = bytes.fromhex("363d3d373d3d3d363d73")
EIP1167_SUFFIX = bytes.fromhex("5af43d82803e903d91602b57fd5bf3")


def proxy_code_hash(implementation: str) -> str:
    """The code hash of every EIP-1167 minimal proxy to [implementation]."""
    code = EIP1167_PREFIX + bytes.fromhex(implementation.removeprefix("0x")) + EIP1167_SUFFIX
    return "0x" + keccak256(code).hex()


def build(verified: list, listed: dict) -> dict:
    networks = {}
    proxied = set()
    for entry in listed["contracts"]:
        networks[entry["chainId"]] = entry["network"]
        if entry.get("eip1167Proxies"):
            proxied.add((entry["chainId"], entry["address"].lower()))
    contracts, proxies = [], []
    for entry in sorted(verified, key=lambda e: (e["chainId"], e["address"])):
        network = networks[entry["chainId"]]
        contracts.append({
            "network": network,
            "address": entry["address"],
            "name": entry["name"],
            "codeHash": entry["codeHash"],
            "functions": entry["functions"],
        })
        if (entry["chainId"], entry["address"]) in proxied:
            proxies.append({
                "network": network,
                "codeHash": proxy_code_hash(entry["address"]),
                "implementation": entry["address"],
                "implementationCodeHash": entry["codeHash"],
            })
    listed_set = {(e["chainId"], e["address"].lower()) for e in listed["contracts"]}
    verified_set = {(e["chainId"], e["address"]) for e in verified}
    if listed_set != verified_set:
        raise SystemExit(f"refused: the list and the recompile differ: listed only {sorted(listed_set - verified_set)}, "
                         f"recompiled only {sorted(verified_set - listed_set)}")
    return {"contracts": contracts, "proxies": proxies}


def kotlin(catalog: dict) -> str:
    text = json.dumps(catalog, sort_keys=True, separators=(",", ":"), ensure_ascii=True)
    digest = hashlib.sha256(text.encode("ascii")).hexdigest()
    chunks = [text[start:start + CHUNK_BYTES] for start in range(0, len(text), CHUNK_BYTES)]
    out = [
        "// Generated by scripts/verified-abis/generate.py. Do not edit by hand.",
        f"// {len(catalog['contracts'])} contracts recompiled from Sourcify's exact matches, and {len(catalog['proxies'])}"
        " EIP-1167 proxies",
        "// to them, each pinned by its runtime code's hash (docs/clear-signing.md, Phase C).",
        "package eth.serotine.data.clearsigning",
        "",
        "/** The sha256 of [VERIFIED_ABI_CATALOG_JSON] joined, which the catalog's reader checks before it parses. */",
        f'internal const val VERIFIED_ABI_CATALOG_SHA256 = "{digest}"',
        "",
        "/**",
        " * The built-in verified-ABI catalog: compact JSON, in chunks a JVM string constant holds. Joined, it is each",
        " * contract's network, address, compiled name, code hash and functions (selector, name, parameters), and each",
        " * EIP-1167 proxy's code hash with its implementation's.",
        " */",
        "internal val VERIFIED_ABI_CATALOG_JSON: List<String> = listOf(",
    ]
    for chunk in chunks:
        assert '"""' not in chunk
        out.append('    """' + chunk.replace("$", "${'$'}") + '""",')
    out.append(")")
    return "\n".join(out) + "\n"


def main(argv: list) -> int:
    if argv not in ([], ["--check"]):
        print(__doc__, file=sys.stderr)
        return 2
    verified = json.loads((HERE / "verified.json").read_text(encoding="utf-8"))
    listed = json.loads((HERE / "contracts.json").read_text(encoding="utf-8"))
    written = kotlin(build(verified, listed))
    if argv == ["--check"]:
        if not TARGET.exists() or TARGET.read_text(encoding="utf-8") != written:
            print(f"{TARGET.relative_to(ROOT)} is not what generate.py writes: run it, and review the diff",
                  file=sys.stderr)
            return 1
        return 0
    TARGET.write_text(written, encoding="utf-8")
    print(f"wrote {TARGET.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
